def basic_answer(text):
    lower = text.lower()
    opener = random.choice(OPENERS).format(s=snippet(text))
    for keywords, body in BASIC_PATTERNS:
        if any(w in lower for w in keywords):
            return opener + "\n\n" + body
    return opener + "\n\n" + random.choice(GENERIC_BODIES)


def concise_advice(body, max_chars=520):
    """긴 기본 답변을 공감 + 현실적인 조언 + 실행 방법 중심으로 짧게 정리."""
    paragraphs = [p.strip() for p in body.split("\n\n") if p.strip()]
    if len(paragraphs) <= 2 and len(body) <= max_chars:
        return body

    # 첫 문단은 공감, 다음 문단들은 조언과 실행 방법을 살려 짧게 추림.
    chosen = paragraphs[:3]
    compact = []
    for index, paragraph in enumerate(chosen):
        sentences = re.split(r'(?<=[.!?])\s+', paragraph)
        # 공감은 짧게, 해결책은 최대 두 문장까지 유지
        take = 1 if index == 0 else 2
        part = " ".join(sentences[:take]).strip()
        limit = 145 if index == 0 else 190
        if len(part) > limit:
            part = part[:limit].rsplit(" ", 1)[0].rstrip(" ,;:") + "…"
        if part:
            compact.append(part)
    result = "\n\n".join(compact)
    return result if len(result) <= max_chars else result[:max_chars].rsplit(" ", 1)[0].rstrip() + "…"


def answer_custom(user_text):
    """(답변 텍스트, 출처) 반환. 출처: 'safety' | 'ai' | 'basic'"""
    text = user_text.strip()
    if is_dangerous(text):
        return safety_response(), "safety"
    ai = ai_answer(text)
    if ai:
        return concise_advice(ai, max_chars=650), "ai"
    return concise_advice(basic_answer(text)), "basic"


